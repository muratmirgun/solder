package codegen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/printer"
	"go/token"
	"go/types"
	"io"
	"maps"
	"slices"
	"strconv"
	"strings"
	"unicode"

	"golang.org/x/tools/go/packages"
)

type emitter struct {
	cur        *types.Package
	imports    map[string]string // path -> local name
	pkgNames   map[string]string // path -> package name
	fileTaken  map[string]bool   // package-scope and import names
	collecting bool              // first pass: only record imports
}

// emit renders the plans of one package as a solder_gen.go file.
func emit(pkg *packages.Package, plans []*plan) ([]byte, error) {
	e := &emitter{cur: pkg.Types, imports: map[string]string{}, pkgNames: map[string]string{}, fileTaken: map[string]bool{}}
	for _, n := range pkg.Types.Scope().Names() {
		e.fileTaken[n] = true
	}
	// Pass 1 records the imports, so variable names can avoid them.
	e.collecting = true
	for _, pl := range plans {
		e.injector(io.Discard, pl)
	}
	e.collecting = false
	for _, path := range slices.Sorted(maps.Keys(e.pkgNames)) {
		e.imports[path] = e.fresh(e.fileTaken, e.pkgNames[path])
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by solder. DO NOT EDIT.\n\n//go:build !solderinject\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg.Types.Name())
	if len(e.imports) > 0 {
		b.WriteString("import (\n")
		for _, path := range slices.Sorted(maps.Keys(e.imports)) {
			if name := e.imports[path]; name != e.pkgNames[path] {
				fmt.Fprintf(&b, "%s ", name)
			}
			fmt.Fprintf(&b, "%q\n", path)
		}
		b.WriteString(")\n\n")
	}
	for _, pl := range plans {
		e.nameVars(pl)
		e.injector(&b, pl)
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("internal error: generated code does not parse: %v\n%s", err, b.Bytes())
	}
	return src, nil
}

func (e *emitter) pkg(path, name string) string {
	if e.collecting {
		e.pkgNames[path] = name
		return name
	}
	return e.imports[path]
}

func (e *emitter) qualifier(p *types.Package) string {
	if p.Path() == e.cur.Path() {
		return ""
	}
	return e.pkg(p.Path(), p.Name())
}

func (e *emitter) typ(t types.Type) string { return types.TypeString(t, e.qualifier) }

func (e *emitter) fn(f *types.Func) string {
	if q := e.qualifier(f.Pkg()); q != "" {
		return q + "." + f.Name()
	}
	return f.Name()
}

func (e *emitter) solder() string { return e.pkg(solderPath, "solder") }

// fresh returns base, or base2, base3..., avoiding taken names, keywords and
// predeclared identifiers, and marks the result taken.
func (e *emitter) fresh(taken map[string]bool, base string) string {
	name := base
	for i := 2; taken[name] || token.IsKeyword(name) || types.Universe.Lookup(name) != nil; i++ {
		name = base + strconv.Itoa(i)
	}
	taken[name] = true
	return name
}

func (e *emitter) nameVars(pl *plan) {
	taken := maps.Clone(e.fileTaken)
	for _, p := range pl.params {
		if p.name != "" {
			taken[p.name] = true
		}
	}
	for _, s := range pl.steps {
		if s.kind == sCall && s.fn.hasErr {
			taken["err"] = true
		}
	}
	for _, p := range pl.params {
		if p.name == "" {
			p.name = e.fresh(taken, baseName(p.typ))
		}
	}
	for _, s := range pl.steps {
		if s.out != nil && s.kind != sHook {
			base := baseName(s.out.typ)
			if s.kind == sApp {
				base = "app"
			}
			s.out.name = e.fresh(taken, base)
		}
	}
}

func (e *emitter) injector(w io.Writer, pl *plan) {
	d := pl.inj.decl
	if d.Doc != nil {
		for _, c := range d.Doc.List {
			fmt.Fprintln(w, c.Text)
		}
	}
	var params []string
	for _, p := range pl.params {
		params = append(params, p.name+" "+e.typ(p.typ))
	}
	res := pl.inj.sig.Results()
	var results []string
	for i := range res.Len() {
		results = append(results, e.typ(res.At(i).Type()))
	}
	resStr := strings.Join(results, ", ")
	if len(results) > 1 {
		resStr = "(" + resStr + ")"
	}
	fmt.Fprintf(w, "func %s(%s) %s {\n", d.Name.Name, strings.Join(params, ", "), resStr)
	for _, s := range pl.steps {
		e.step(w, pl, s)
	}
	ret := e.ref(pl.result)
	if pl.returnsApp {
		ret = pl.app.name
	}
	if pl.hasErr {
		ret += ", nil"
	}
	fmt.Fprintf(w, "return %s\n}\n\n", ret)
}

func (e *emitter) step(w io.Writer, pl *plan, s step) {
	switch s.kind {
	case sApp:
		fmt.Fprintf(w, "%s := %s.New()\n", s.out.name, e.solder())
	case sSupply:
		fmt.Fprintf(w, "%s := %s\n", s.out.name, e.expr(s.supply))
	case sGroup:
		if len(s.elems) == 0 {
			fmt.Fprintf(w, "var %s %s\n", s.out.name, e.typ(s.out.typ))
			return
		}
		var elems []string
		for _, r := range s.elems {
			elems = append(elems, e.ref(r))
		}
		fmt.Fprintf(w, "%s := %s{%s}\n", s.out.name, e.typ(s.out.typ), strings.Join(elems, ", "))
	case sHook:
		var fields []string
		if s.start {
			fields = append(fields, "OnStart: "+s.out.name+".Start")
		}
		if s.stop {
			fields = append(fields, "OnStop: "+s.out.name+".Stop")
		}
		fmt.Fprintf(w, "%s.Append(%s.Hook{%s})\n", pl.app.name, e.solder(), strings.Join(fields, ", "))
	case sCall:
		call := e.fn(s.fn.obj) + "(" + e.args(pl, s.args) + ")"
		switch {
		case s.out == nil && s.fn.hasErr:
			fmt.Fprintf(w, "if err := %s; err != nil {\nreturn %s\n}\n", call, e.failure(pl))
		case s.out == nil:
			fmt.Fprintln(w, call)
		case s.fn.hasErr:
			fmt.Fprintf(w, "%s, err := %s\nif err != nil {\nreturn %s\n}\n", s.out.name, call, e.failure(pl))
		default:
			fmt.Fprintf(w, "%s := %s\n", s.out.name, call)
		}
	}
}

func (e *emitter) args(pl *plan, args []arg) string {
	var out []string
	for _, a := range args {
		switch {
		case a.app:
			out = append(out, pl.app.name)
		case a.inType != nil:
			var fields []string
			for _, f := range a.fields {
				fields = append(fields, f.name+": "+e.ref(f.ref))
			}
			out = append(out, e.typ(a.inType)+"{"+strings.Join(fields, ", ")+"}")
		default:
			out = append(out, e.ref(a.ref))
		}
	}
	return strings.Join(out, ", ")
}

func (e *emitter) ref(r ref) string {
	if r.v == nil {
		return ""
	}
	if r.field != "" {
		return r.v.name + "." + r.field
	}
	return r.v.name
}

// failure is the return statement operand list after an error.
func (e *emitter) failure(pl *plan) string {
	res := pl.inj.sig.Results()
	var out []string
	for i := range res.Len() - 1 {
		out = append(out, e.zero(res.At(i).Type()))
	}
	return strings.Join(append(out, "err"), ", ")
}

func (e *emitter) zero(t types.Type) string {
	switch u := types.Unalias(t).Underlying().(type) {
	case *types.Basic:
		switch {
		case u.Info()&types.IsBoolean != 0:
			return "false"
		case u.Info()&types.IsString != 0:
			return `""`
		case u.Info()&types.IsNumeric != 0:
			return "0"
		}
	case *types.Struct, *types.Array:
		return e.typ(t) + "{}"
	}
	return "nil"
}

// expr prints a Supply expression with package names rewritten to this
// file's imports.
func (e *emitter) expr(p *producer) string {
	ast.Inspect(p.expr, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok {
				if pn, ok := p.pkg.TypesInfo.Uses[id].(*types.PkgName); ok {
					id.Name = e.pkg(pn.Imported().Path(), pn.Imported().Name())
				}
			}
		}
		return true
	})
	var b bytes.Buffer
	printer.Fprint(&b, p.pkg.Fset, p.expr)
	return b.String()
}

// baseName suggests a variable name for a value of type t.
func baseName(t types.Type) string {
	t = types.Unalias(t)
	for {
		p, ok := t.(*types.Pointer)
		if !ok {
			break
		}
		t = types.Unalias(p.Elem())
	}
	switch x := t.(type) {
	case *types.Named:
		return lowerFirst(x.Obj().Name())
	case *types.Slice:
		return baseName(x.Elem()) + "s"
	}
	return "v"
}

// lowerFirst lowercases a leading capital or acronym: Config→config,
// DB→db, HTTPServer→httpServer, DBs→dbs.
func lowerFirst(s string) string {
	r := []rune(s)
	n := 0
	for n < len(r) && unicode.IsUpper(r[n]) {
		n++
	}
	if n > 1 && n < len(r) && !(n == len(r)-1 && r[n] == 's') {
		n-- // keep the capital that starts the next word
	}
	for i := range n {
		r[i] = unicode.ToLower(r[i])
	}
	return string(r)
}
